// AUTO-RUNS before every deploy (see package.json predeploy)
// Drop a .png into assets/Workout Images/ using underscores for spaces
// (e.g. Incline_Dumbbell_Press.png) then run npm run deploy — nothing else needed.

const fs   = require('fs')
const path = require('path')

const imagesDir = path.join(__dirname, '..', 'assets', 'Workout Images')
const outFile   = path.join(__dirname, '..', 'src', 'data', 'workoutImages.js')

const files = fs.readdirSync(imagesDir)
  .filter((f) => /\.(png|jpg|jpeg|webp)$/i.test(f))
  .sort()

const entries = files.map((f) => {
  const exerciseName = f.replace(/\.[^.]+$/, '').replace(/_/g, ' ')
  return `  '${exerciseName}': require('../../assets/Workout Images/${f}'),`
})

const content = `// AUTO-GENERATED by scripts/generate-image-map.js — do not edit manually.
// To add an image: drop Underscored_Name.png into assets/Workout Images/ and redeploy.

const workoutImages = {
${entries.join('\n')}
}

export default workoutImages
`

fs.writeFileSync(outFile, content)
console.log(`✓ workoutImages.js generated (${files.length} image(s): ${files.join(', ')})`)
